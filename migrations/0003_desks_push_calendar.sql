-- Friendly desk names, shared by everyone (the same desk QR is the same desk for all).
CREATE TABLE desk_names (
  eui64 TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  named_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Web push subscriptions, one per installed device.
CREATE TABLE push_subscriptions (
  endpoint TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX push_user ON push_subscriptions(user_id);

-- App-wide settings generated by the app itself (e.g. the VAPID key pair for push).
CREATE TABLE app_config (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Reminder preferences: ISO weekday (1 = Monday) and local hour; NULL day = off.
ALTER TABLE users ADD COLUMN remind_day INTEGER DEFAULT 4;
ALTER TABLE users ADD COLUMN remind_hour INTEGER NOT NULL DEFAULT 8;
-- Start date of the week the last reminder was sent for, so it is sent once a week.
ALTER TABLE users ADD COLUMN reminded_for TEXT;
-- Secret token for the private calendar feed URL.
ALTER TABLE users ADD COLUMN calendar_token TEXT;
CREATE UNIQUE INDEX users_calendar_token ON users(calendar_token);
